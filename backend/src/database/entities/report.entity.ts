import {
  Column,
  CreateDateColumn,
  Entity,
  JoinColumn,
  OneToMany,
  OneToOne,
  PrimaryGeneratedColumn,
  Unique,
  UpdateDateColumn,
  type Relation,
} from 'typeorm';
import { ExtractionMethod } from '../enums.js';
import { numericTransformer } from '../numeric.transformer.js';
import { Document } from './document.entity.js';
import { ReportParameter } from './report-parameter.entity.js';

export interface ReportWarning {
  code: string;
  message: string;
}

/** The data extracted from a document. Created only when extraction succeeds. */
@Entity('reports')
@Unique(['labName', 'reportId'])
export class Report {
  @PrimaryGeneratedColumn('uuid')
  id: string;

  @Column({ name: 'document_fk', type: 'uuid', unique: true })
  documentFk: string;

  @OneToOne(() => Document, (document) => document.report, { onDelete: 'CASCADE' })
  @JoinColumn({ name: 'document_fk' })
  document: Relation<Document>;

  /** Report / Sample ID printed on the PDF, or AUTO-<date>-<hash> when missing. */
  @Column({ name: 'report_id', type: 'varchar', length: 100 })
  reportId: string;

  @Column({ name: 'id_auto_generated', type: 'boolean', default: false })
  idAutoGenerated: boolean;

  @Column({ name: 'patient_name', type: 'varchar', length: 200, nullable: true })
  patientName: string | null;

  @Column({ name: 'report_date', type: 'date', nullable: true })
  reportDate: string | null;

  /** NOT NULL on purpose: PostgreSQL treats NULLs as distinct, which would bypass UNIQUE(lab_name, report_id). */
  @Column({ name: 'lab_name', type: 'varchar', length: 200, default: 'UNKNOWN' })
  labName: string;

  @Column({ name: 'page_count', type: 'int' })
  pageCount: number;

  @Column({ name: 'extraction_method', type: 'enum', enum: ExtractionMethod, enumName: 'extraction_method' })
  extractionMethod: ExtractionMethod;

  @Column({
    name: 'parse_score',
    type: 'numeric',
    precision: 4,
    scale: 3,
    nullable: true,
    transformer: numericTransformer,
  })
  parseScore: number | null;

  @Column({ type: 'jsonb', default: () => `'[]'::jsonb` })
  warnings: ReportWarning[];

  @Column({ name: 'raw_text', type: 'text', default: '' })
  rawText: string;

  @CreateDateColumn({ name: 'created_at', type: 'timestamptz' })
  createdAt: Date;

  @UpdateDateColumn({ name: 'updated_at', type: 'timestamptz' })
  updatedAt: Date;

  @OneToMany(() => ReportParameter, (parameter) => parameter.report)
  parameters: Relation<ReportParameter[]>;
}
