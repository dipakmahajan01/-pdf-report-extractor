import type { Document } from '../database/entities/document.entity.js';
import type { ExtractionAttempt } from '../database/entities/extraction-attempt.entity.js';
import type { ReportParameter } from '../database/entities/report-parameter.entity.js';
import type { Report } from '../database/entities/report.entity.js';
import { DocumentStatus } from '../database/enums.js';
import { MAX_ATTEMPTS } from './documents.constants.js';

// Response shapes are mapped explicitly so internal columns (file path, hash) never reach the client.

export function toDocumentSummary(d: Document, parameterCount: number) {
  return {
    id: d.id,
    fileName: d.fileName,
    fileSizeBytes: d.fileSizeBytes,
    status: d.status,
    attemptCount: d.attemptCount,
    lastErrorCode: d.lastErrorCode,
    lastErrorMessage: d.lastErrorMessage,
    canRetry: canRetry(d),
    createdAt: d.createdAt,
    updatedAt: d.updatedAt,
    report: d.report
      ? {
          reportId: d.report.reportId,
          idAutoGenerated: d.report.idAutoGenerated,
          patientName: d.report.patientName,
          reportDate: d.report.reportDate,
          labName: d.report.labName,
          extractionMethod: d.report.extractionMethod,
          parameterCount,
        }
      : null,
  };
}

export function toDocumentDetail(d: Document) {
  return {
    ...toDocumentSummary(d, d.report?.parameters?.filter((p) => !p.isSection).length ?? 0),
    report: d.report ? toReport(d.report) : null,
    attempts: (d.attempts ?? []).map(toAttempt),
  };
}

function toReport(r: Report) {
  return {
    id: r.id,
    reportId: r.reportId,
    idAutoGenerated: r.idAutoGenerated,
    patientName: r.patientName,
    reportDate: r.reportDate,
    labName: r.labName,
    pageCount: r.pageCount,
    extractionMethod: r.extractionMethod,
    parseScore: r.parseScore,
    warnings: r.warnings,
    rawText: r.rawText,
    createdAt: r.createdAt,
    parameters: (r.parameters ?? []).map(toParameter),
  };
}

function toParameter(p: ReportParameter) {
  return {
    rowOrder: p.rowOrder,
    pageNumber: p.pageNumber,
    isSection: p.isSection,
    sectionName: p.sectionName,
    name: p.name,
    nameNormalized: p.nameNormalized,
    valueRaw: p.valueRaw,
    valueNumeric: p.valueNumeric,
    comparator: p.comparator,
    unit: p.unit,
    refRangeRaw: p.refRangeRaw,
    refLow: p.refLow,
    refHigh: p.refHigh,
    flag: p.flag,
    ocrConfidence: p.ocrConfidence,
    extra: p.extra,
  };
}

function toAttempt(a: ExtractionAttempt) {
  return {
    attemptNo: a.attemptNo,
    status: a.status,
    failedStage: a.failedStage,
    errorCode: a.errorCode,
    errorMessage: a.errorMessage,
    extractionMethod: a.extractionMethod,
    rowsFound: a.rowsFound,
    parseScore: a.parseScore,
    durationMs: a.durationMs,
    startedAt: a.startedAt,
    finishedAt: a.finishedAt,
  };
}

function canRetry(d: Document): boolean {
  return d.status === DocumentStatus.Failed && d.isRetryable && d.attemptCount < MAX_ATTEMPTS;
}

export type DocumentSummary = ReturnType<typeof toDocumentSummary>;
export type DocumentDetail = ReturnType<typeof toDocumentDetail>;
