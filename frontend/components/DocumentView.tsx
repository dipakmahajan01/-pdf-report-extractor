'use client';

import Link from 'next/link';
import { useParams, useRouter } from 'next/navigation';
import { useCallback, useEffect, useState } from 'react';
import { api, ApiError, formatDate, type DocumentDetail } from '@/lib/api';
import { ParametersTable } from './ParametersTable';
import { MethodBadge, StatusBadge } from './StatusBadge';

export function DocumentView() {
  const { id } = useParams<{ id: string }>();
  const router = useRouter();
  const [doc, setDoc] = useState<DocumentDetail | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [actionError, setActionError] = useState<string | null>(null);
  const [busy, setBusy] = useState<'retry' | 'delete' | null>(null);

  const load = useCallback(async () => {
    try {
      setDoc(await api.get(id));
      setError(null);
    } catch (e) {
      setError(e instanceof ApiError ? e.message : 'Could not load the document');
    }
  }, [id]);

  useEffect(() => {
    load();
  }, [load]);

  async function retry() {
    setBusy('retry');
    setActionError(null);
    try {
      setDoc(await api.retry(id));
    } catch (e) {
      setActionError(e instanceof ApiError ? e.message : 'Retry failed');
      await load();
    } finally {
      setBusy(null);
    }
  }

  async function remove() {
    setBusy('delete');
    try {
      await api.remove(id);
      router.push('/');
    } catch (e) {
      setActionError(e instanceof ApiError ? e.message : 'Delete failed');
      setBusy(null);
    }
  }

  if (error) {
    return (
      <div className="rounded-xl border border-red-200 bg-red-50 p-5 text-sm text-red-800">
        {error}{' '}
        <Link href="/" className="font-medium underline">
          Back to reports
        </Link>
      </div>
    );
  }
  if (!doc) return <p className="text-sm text-slate-500">Loading…</p>;

  const report = doc.report;
  const dataRows = report?.parameters.filter((p) => !p.isSection).length ?? 0;

  return (
    <div className="grid gap-5">
      <div className="flex flex-wrap items-start justify-between gap-3">
        <div>
          <Link href="/" className="text-sm text-sky-700 hover:underline">
            ← All reports
          </Link>
          <h1 className="mt-1 flex flex-wrap items-center gap-2 text-xl font-semibold text-slate-900">
            {report?.reportId ?? doc.fileName}
            <StatusBadge status={doc.status} />
            {report?.idAutoGenerated && (
              <span className="rounded bg-amber-100 px-1.5 py-0.5 text-xs font-medium text-amber-800">auto-generated ID</span>
            )}
          </h1>
          <p className="mt-0.5 text-sm text-slate-500">{doc.fileName}</p>
        </div>
        <div className="flex gap-2">
          {doc.canRetry && (
            <button
              type="button"
              onClick={retry}
              disabled={busy !== null}
              className="rounded-md bg-slate-900 px-3 py-1.5 text-sm font-medium text-white hover:bg-slate-700 disabled:opacity-50"
            >
              {busy === 'retry' ? 'Retrying… (up to 30 s)' : 'Retry extraction'}
            </button>
          )}
          <button
            type="button"
            onClick={remove}
            disabled={busy !== null}
            className="rounded-md border border-slate-300 bg-white px-3 py-1.5 text-sm font-medium text-slate-700 hover:border-red-300 hover:text-red-700 disabled:opacity-50"
          >
            Delete
          </button>
        </div>
      </div>

      {actionError && <Banner tone="red">{actionError}</Banner>}
      {doc.status === 'failed' && (
        <Banner tone="red">
          <strong>Extraction failed.</strong> {doc.lastErrorMessage}{' '}
          {doc.canRetry
            ? 'The file is stored, so you can retry without uploading it again.'
            : 'This document cannot be retried.'}
        </Banner>
      )}
      {report?.warnings.map((w) => (
        <Banner key={w.code + w.message} tone={w.code === 'NEEDS_REVIEW' || w.code === 'ID_AUTO_GENERATED' ? 'amber' : 'slate'}>
          {w.message}
        </Banner>
      ))}

      {report && (
        <dl className="grid grid-cols-2 gap-x-6 gap-y-3 rounded-xl border border-slate-200 bg-white p-5 text-sm shadow-sm sm:grid-cols-3 lg:grid-cols-6">
          <Field label="Patient" value={report.patientName} />
          <Field label="Report date" value={formatDate(report.reportDate)} />
          <Field label="Lab" value={report.labName} />
          <Field label="Tests" value={String(dataRows)} />
          <Field label="Pages" value={String(report.pageCount)} />
          <div>
            <dt className="text-xs text-slate-500">Read with</dt>
            <dd className="mt-1">
              <MethodBadge method={report.extractionMethod} />
            </dd>
          </div>
        </dl>
      )}

      <div className="grid gap-5 xl:grid-cols-2">
        <section className="overflow-hidden rounded-xl border border-slate-200 bg-white shadow-sm">
          <h2 className="border-b border-slate-200 px-4 py-3 text-sm font-semibold text-slate-900">Original PDF</h2>
          <iframe src={api.fileUrl(doc.id)} title="Original PDF" className="h-[75vh] w-full bg-slate-100" />
        </section>

        <section className="overflow-hidden rounded-xl border border-slate-200 bg-white shadow-sm">
          <h2 className="border-b border-slate-200 px-4 py-3 text-sm font-semibold text-slate-900">Extracted data</h2>
          {report ? (
            <ParametersTable parameters={report.parameters} />
          ) : (
            <p className="px-4 py-6 text-sm text-slate-500">No data was extracted from this document.</p>
          )}
        </section>
      </div>

      <section className="rounded-xl border border-slate-200 bg-white shadow-sm">
        <h2 className="border-b border-slate-200 px-4 py-3 text-sm font-semibold text-slate-900">Processing history</h2>
        <ul className="divide-y divide-slate-100 text-sm">
          {doc.attempts.map((a) => (
            <li key={a.attemptNo} className="flex flex-wrap items-baseline gap-x-3 gap-y-1 px-4 py-2.5">
              <span className="font-medium text-slate-700">Attempt {a.attemptNo}</span>
              <span className={a.status === 'success' ? 'text-emerald-700' : a.status === 'failed' ? 'text-red-700' : 'text-sky-700'}>
                {a.status}
              </span>
              {a.rowsFound !== null && <span className="text-slate-500">{a.rowsFound} tests</span>}
              {a.failedStage && <span className="text-slate-500">failed at: {a.failedStage}</span>}
              {a.errorCode && <code className="rounded bg-slate-100 px-1 text-xs text-slate-600">{a.errorCode}</code>}
              {a.durationMs !== null && <span className="text-slate-400">{(a.durationMs / 1000).toFixed(1)} s</span>}
              <span className="ml-auto text-slate-400">{formatDate(a.startedAt)}</span>
            </li>
          ))}
        </ul>
      </section>

      {report?.rawText && (
        <details className="rounded-xl border border-slate-200 bg-white shadow-sm">
          <summary className="cursor-pointer px-4 py-3 text-sm font-semibold text-slate-900">Raw extracted text</summary>
          <pre className="max-h-96 overflow-auto border-t border-slate-200 bg-slate-50 px-4 py-3 text-xs leading-relaxed text-slate-700">
            {report.rawText}
          </pre>
        </details>
      )}
    </div>
  );
}

function Field({ label, value }: { label: string; value: string | null }) {
  return (
    <div>
      <dt className="text-xs text-slate-500">{label}</dt>
      <dd className="mt-1 font-medium text-slate-900">{value ?? '—'}</dd>
    </div>
  );
}

const TONES = {
  red: 'border-red-200 bg-red-50 text-red-800',
  amber: 'border-amber-200 bg-amber-50 text-amber-900',
  slate: 'border-slate-200 bg-white text-slate-700',
};

function Banner({ tone, children }: { tone: keyof typeof TONES; children: React.ReactNode }) {
  return <div className={`rounded-lg border px-4 py-2.5 text-sm ${TONES[tone]}`}>{children}</div>;
}
