export const API_URL = process.env.NEXT_PUBLIC_API_URL ?? 'http://localhost:4000/api';

export type DocumentStatus = 'processing' | 'completed' | 'needs_review' | 'failed';

export interface ReportSummary {
  reportId: string;
  idAutoGenerated: boolean;
  patientName: string | null;
  reportDate: string | null;
  labName: string;
  extractionMethod: 'text' | 'ocr' | 'mixed';
  parameterCount: number;
}

export interface DocumentSummary {
  id: string;
  fileName: string;
  fileSizeBytes: number;
  status: DocumentStatus;
  attemptCount: number;
  lastErrorCode: string | null;
  lastErrorMessage: string | null;
  canRetry: boolean;
  createdAt: string;
  updatedAt: string;
  report: ReportSummary | null;
}

export interface Parameter {
  rowOrder: number;
  pageNumber: number;
  isSection: boolean;
  sectionName: string | null;
  name: string;
  nameNormalized: string;
  valueRaw: string | null;
  valueNumeric: number | null;
  comparator: string | null;
  unit: string | null;
  refRangeRaw: string | null;
  refLow: number | null;
  refHigh: number | null;
  flag: 'H' | 'L' | null;
  ocrConfidence: number | null;
  extra: Record<string, string> | null;
}

export interface Attempt {
  attemptNo: number;
  status: 'running' | 'success' | 'failed';
  failedStage: string | null;
  errorCode: string | null;
  errorMessage: string | null;
  extractionMethod: string | null;
  rowsFound: number | null;
  parseScore: number | null;
  durationMs: number | null;
  startedAt: string;
  finishedAt: string | null;
}

export interface DocumentDetail extends Omit<DocumentSummary, 'report'> {
  report:
    | (Omit<ReportSummary, 'parameterCount'> & {
        id: string;
        pageCount: number;
        parseScore: number | null;
        warnings: { code: string; message: string }[];
        rawText: string;
        createdAt: string;
        parameters: Parameter[];
      })
    | null;
  attempts: Attempt[];
}

export interface Paginated<T> {
  items: T[];
  page: number;
  limit: number;
  total: number;
}

/** Error returned by the API: `code` is stable, `message` is for people. */
export class ApiError extends Error {
  constructor(
    readonly status: number,
    readonly code: string,
    message: string,
    readonly body: Record<string, unknown> = {},
  ) {
    super(message);
  }
}

async function request<T>(path: string, init?: RequestInit): Promise<T> {
  let res: Response;
  try {
    res = await fetch(`${API_URL}${path}`, { cache: 'no-store', ...init });
  } catch {
    throw new ApiError(0, 'NETWORK_ERROR', 'Cannot reach the API. Is the backend running on port 4000?');
  }
  if (res.status === 204) return undefined as T;
  const body = await res.json().catch(() => ({}));
  if (!res.ok) throw new ApiError(res.status, body.code ?? 'ERROR', body.message ?? `Request failed (${res.status})`, body);
  return body as T;
}

export const api = {
  list: (page = 1, limit = 50) => request<Paginated<DocumentSummary>>(`/documents?page=${page}&limit=${limit}`),
  get: (id: string) => request<DocumentDetail>(`/documents/${id}`),
  retry: (id: string) => request<DocumentDetail>(`/documents/${id}/retry`, { method: 'POST' }),
  remove: (id: string) => request<void>(`/documents/${id}`, { method: 'DELETE' }),
  fileUrl: (id: string) => `${API_URL}/documents/${id}/file`,

  /** XMLHttpRequest instead of fetch, because fetch cannot report upload progress. */
  upload(file: File, onProgress: (percent: number) => void): Promise<DocumentDetail> {
    return new Promise((resolve, reject) => {
      const xhr = new XMLHttpRequest();
      xhr.open('POST', `${API_URL}/documents/upload`);
      xhr.upload.onprogress = (e) => e.lengthComputable && onProgress(Math.round((e.loaded / e.total) * 100));
      xhr.onerror = () => reject(new ApiError(0, 'NETWORK_ERROR', 'Cannot reach the API. Is the backend running on port 4000?'));
      xhr.onload = () => {
        let body: Record<string, unknown> = {};
        try {
          body = JSON.parse(xhr.responseText);
        } catch {}
        if (xhr.status >= 200 && xhr.status < 300) resolve(body as unknown as DocumentDetail);
        else reject(new ApiError(xhr.status, String(body.code ?? 'ERROR'), String(body.message ?? 'Upload failed'), body));
      };
      const form = new FormData();
      form.append('file', file);
      xhr.send(form);
    });
  },
};

export function formatDate(iso: string | null): string {
  if (!iso) return '—';
  const d = new Date(iso.length === 10 ? `${iso}T00:00:00` : iso);
  return iso.length === 10
    ? d.toLocaleDateString('en-IN', { day: '2-digit', month: 'short', year: 'numeric' })
    : d.toLocaleString('en-IN', { day: '2-digit', month: 'short', hour: '2-digit', minute: '2-digit' });
}
